// Declarar as variáveis
let entA: string;
let entB: string;
let A: number;
let B: number;
let SOMA: number;

// Entrada de dados
entA = prompt('Digite A: ')!;
entB = prompt('Digite B: ')!;

// Processamento dos dados
A = parseInt(entA);
B = parseInt(entB);
SOMA = A + B;

// Saída de dados
console.log(`SOMA = ${SOMA}`);
